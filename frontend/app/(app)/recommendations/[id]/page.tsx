"use client";

/**
 * A persisted recommendation run.
 *
 * Reads from `GET /api/recommendations/runs/{id}` and never recomputes. A stored
 * run is a historical record: recomputing it would silently change the numbers if
 * the knowledge base was edited between the run and this page view, which would
 * make the run history a fiction.
 */
import { useParams, useRouter } from "next/navigation";
import Link from "next/link";
import { ArrowLeft, ExternalLink } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Progress } from "@/components/ui/progress";
import { ErrorState } from "@/components/shared/ErrorState";
import { LoadingCards } from "@/components/shared/Loading";
import { PageHeader } from "@/components/shared/PageHeader";
import { ScoreBreakdown } from "@/features/recommendations/ScoreBreakdown";
import { useRun } from "@/lib/hooks/use-recommendations";

export default function RunDetailPage() {
  const params = useParams<{ id: string }>();
  const router = useRouter();
  const runId = Number(params?.id);
  const run = useRun(Number.isFinite(runId) ? runId : null);

  if (run.isPending) {
    return (
      <div className="space-y-6">
        <PageHeader title="Recommendation run" description="Loading…" />
        <LoadingCards count={3} />
      </div>
    );
  }

  if (run.isError) {
    return (
      <div className="space-y-4">
        <PageHeader title="Recommendation run" />
        <ErrorState error={run.error} onRetry={() => void run.refetch()} />
        <p className="text-sm text-muted-foreground">
          If the run does not exist, it may have been generated by a different account — runs
          are only visible to the user who created them.
        </p>
      </div>
    );
  }

  const data = run.data;
  const snapshot = (data.profile_snapshot ?? {}) as {
    skills?: { name: string; proficiency: number }[];
    projects?: { title: string }[];
    education?: { institution: string; degree: string }[];
    skill_count?: number;
  };

  return (
    <div className="space-y-6">
      <PageHeader
        title="Recommendation run"
        description={`Generated ${new Date(data.created_at).toLocaleString()} · engine ${data.engine_version}`}
        actions={
          <>
            <Button variant="outline" asChild>
              <Link href="/recommendations">
                <ArrowLeft className="mr-2 h-4 w-4" aria-hidden="true" />
                All runs
              </Link>
            </Button>
            <Button asChild>
              <Link href="/recommendations">Generate a new run</Link>
            </Button>
          </>
        }
      />

      <div className="grid gap-4 sm:grid-cols-4">
        {[
          { label: "Candidates scored", value: data.total_candidates },
          { label: "Coverage weight", value: data.weights.skill_coverage },
          { label: "TF-IDF weight", value: data.weights.tfidf_similarity },
          { label: "Duration", value: data.duration_ms != null ? `${data.duration_ms} ms` : "—" },
        ].map((stat) => (
          <Card key={stat.label}>
            <CardContent className="p-4">
              <p className="text-sm text-muted-foreground">{stat.label}</p>
              <p className="text-2xl font-bold">{stat.value}</p>
            </CardContent>
          </Card>
        ))}
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Profile at the time of this run</CardTitle>
          <CardDescription>
            Stored with the run so a later edit to your profile cannot change what this run
            actually saw.
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-3">
          <p className="text-sm text-muted-foreground">
            {snapshot.skill_count ?? snapshot.skills?.length ?? 0} skill(s) ·{" "}
            {snapshot.projects?.length ?? 0} project(s) · {snapshot.education?.length ?? 0}{" "}
            education record(s)
          </p>
          {snapshot.skills && snapshot.skills.length > 0 ? (
            <div className="flex flex-wrap gap-1.5">
              {snapshot.skills.slice(0, 20).map((skill) => (
                <Badge key={skill.name} variant="secondary">
                  {skill.name} · {skill.proficiency}/5
                </Badge>
              ))}
            </div>
          ) : null}
        </CardContent>
      </Card>

      <section className="space-y-3" aria-labelledby="ranked-heading">
        <h2 id="ranked-heading" className="text-lg font-semibold">
          Full ranked list
        </h2>
        {data.results.length === 0 ? (
          <p className="text-sm text-muted-foreground">This run produced no results.</p>
        ) : (
          <div className="space-y-3">
            {data.results.map((role) => (
              <Card key={role.job_role_id}>
                <CardContent className="space-y-3 p-5">
                  <div className="flex flex-wrap items-start justify-between gap-4">
                    <div className="min-w-0 space-y-1">
                      <div className="flex flex-wrap items-center gap-2">
                        <span className="text-sm font-semibold text-muted-foreground">#{role.rank}</span>
                        <h3 className="text-lg font-semibold">{role.title}</h3>
                        <Badge variant="outline">{role.family}</Badge>
                      </div>
                      <p className="text-sm text-muted-foreground">
                        {role.matched_skills.length} matched · {role.missing_skills.length} missing
                      </p>
                    </div>
                    <div className="text-right">
                      <p className="text-3xl font-bold text-primary">{role.compatibility_pct}%</p>
                      <p className="text-xs text-muted-foreground">compatibility</p>
                    </div>
                  </div>

                  <Progress value={role.compatibility_pct} aria-label={`${role.title}: ${role.compatibility_pct}%`} />

                  <div className="grid gap-4 sm:grid-cols-2">
                    <div>
                      <p className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                        Matched
                      </p>
                      {role.matched_skills.length === 0 ? (
                        <p className="text-sm text-muted-foreground">None.</p>
                      ) : (
                        <ul className="space-y-1">
                          {role.matched_skills.map((skill) => (
                            <li key={skill.skill_id} className="flex justify-between gap-2 text-sm">
                              <span className="truncate">{skill.name}</span>
                              <span className="shrink-0 text-xs text-muted-foreground">
                                w {skill.weight} · {skill.proficiency}/5
                              </span>
                            </li>
                          ))}
                        </ul>
                      )}
                    </div>
                    <div>
                      <p className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                        Missing
                      </p>
                      {role.missing_skills.length === 0 ? (
                        <p className="text-sm text-muted-foreground">None.</p>
                      ) : (
                        <ul className="space-y-1">
                          {role.missing_skills.map((skill) => (
                            <li key={skill.skill_id} className="flex justify-between gap-2 text-sm">
                              <span className="truncate">{skill.name}</span>
                              <span className="shrink-0 text-xs text-muted-foreground">w {skill.weight}</span>
                            </li>
                          ))}
                        </ul>
                      )}
                    </div>
                  </div>

                  <div className="flex flex-wrap items-center gap-2">
                    <Button asChild variant="outline" size="sm">
                      <Link href={`/skill-gap?role=${role.job_role_id}`}>
                        Open the skill gap
                        <ExternalLink className="ml-1.5 h-3.5 w-3.5" aria-hidden="true" />
                      </Link>
                    </Button>
                  </div>

                  {role.feedback_samples > 0 ? (
                    <p className="text-xs text-muted-foreground">
                      {role.feedback_samples} user{role.feedback_samples === 1 ? "" : "s"} have
                      said something about this role, giving a community prior of{" "}
                      <span className="font-mono">{role.role_prior.toFixed(3)}</span>.
                    </p>
                  ) : null}

                  <ScoreBreakdown role={role} />
                </CardContent>
              </Card>
            ))}
          </div>
        )}
      </section>

      <div className="flex justify-center">
        <Button variant="ghost" onClick={() => router.back()}>
          <ArrowLeft className="mr-2 h-4 w-4" aria-hidden="true" />
          Go back
        </Button>
      </div>
    </div>
  );
}
